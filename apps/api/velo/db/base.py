"""Declarative base and the column conventions of DATA-MODEL.md §1.

Models live with their domain (``velo/domains/<domain>/models.py``) and never
declare relationships across domains: a foreign key names the other table as a
string, so one domain never imports another's models (ARCHITECTURE.md §3,
rule 5).
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any, ClassVar

from sqlalchemy import CheckConstraint, DateTime, MetaData, Text, Uuid, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from velo.db.ids import uuid7

# Every constraint gets a predictable name, so Alembic can drop and alter it,
# and autogenerated migrations diff cleanly. Check constraints must be given a
# short name; the convention prefixes the table.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

JsonObject = dict[str, Any]


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    type_annotation_map: ClassVar[dict[Any, Any]] = {
        str: Text,
        datetime: DateTime(timezone=True),  # TIMESTAMPTZ, always (DATA-MODEL.md §1)
        uuid.UUID: Uuid,
        JsonObject: JSONB,
    }

    # Server-side defaults (now(), 'draft', …) are read back with RETURNING in
    # the same INSERT, so an async session never lazy-loads them afterwards.
    __mapper_args__ = {"eager_defaults": True}  # noqa: RUF012 — read by the mapper, never mutated


# ── Column conventions ────────────────────────────────────────────────────────
# Mixins, so a table states which audit columns it has in its class line. The
# sort order keeps ``id`` first and the timestamps last in CREATE TABLE.


class HasId:
    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True,
        default=uuid7,
        server_default=text("uuidv7()"),
        sort_order=-100,
        insert_sentinel=True,
    )


class HasCreatedAt:
    created_at: Mapped[datetime] = mapped_column(server_default=func.now(), sort_order=100)


class HasTimestamps(HasCreatedAt):
    updated_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), onupdate=func.now(), sort_order=101
    )


class SoftDeletable:
    """Catalog only. Orders and payments are never soft-deleted (DATA-MODEL.md §1)."""

    deleted_at: Mapped[datetime | None] = mapped_column(sort_order=102)


def json_object(name: str | None = None) -> Mapped[JsonObject]:
    """A ``JSONB NOT NULL DEFAULT '{}'`` column."""
    if name is None:
        return mapped_column(server_default=text("'{}'::jsonb"))
    return mapped_column(name, server_default=text("'{}'::jsonb"))


def one_of(column: str, *values: str, name: str | None = None) -> CheckConstraint:
    """``CHECK (column IN (...))`` — the status-column rule of DATA-MODEL.md §1.

    TEXT plus a CHECK rather than a Postgres enum: extending a CHECK is one
    migration, while an enum value can be added but never removed or reordered.
    """
    allowed = ",".join(f"'{value}'" for value in values)
    return CheckConstraint(f"{column} IN ({allowed})", name=name or f"{column}_valid")


def non_negative(*columns: str) -> list[CheckConstraint]:
    return [CheckConstraint(f"{column} >= 0", name=f"{column}_non_negative") for column in columns]
